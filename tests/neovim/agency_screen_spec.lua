package.path = vim.env.DOTFILES_TEST_ROOT .. "/tests/neovim/?.lua;" .. package.path
dofile(vim.env.DOTFILES_TEST_ROOT .. "/home/.config/nvim/lua/sodium/plugins/agentic.lua").config()
require("snacks").setup({ picker = vim.tbl_extend("force", dofile(vim.env.DOTFILES_TEST_ROOT .. "/home/.config/nvim/lua/sodium/plugins/pickers.lua").opts.picker, { enabled = true }) })

describe("Agency screen", function()
    local f, screen, lines, home, select_ui
    local readme = vim.env.DOTFILES_TEST_ROOT .. "/README.md"
    before_each(function()
        home, select_ui = vim.env.HOME, vim.ui.select
        lines = vim.o.lines
        vim.o.lines = 60
        f = require("fixtures.agency_native").new()
        screen = require("sodium.agency.screen")
    end)
    after_each(function()
        vim.env.HOME, vim.ui.select = home, select_ui
        vim.o.lines = lines
        f.close()
    end)
    local function editor()
        for _, win in ipairs(vim.api.nvim_tabpage_list_wins(0)) do
            if vim.w[win].agentic_bufnr == nil and vim.api.nvim_win_get_config(win).relative == "" then
                return win
            end
        end
    end
    local function half()
        return math.floor(vim.o.lines * 0.5)
    end

    it("derives conversation, split, document and none from the windows in the tab", function()
        assert.are.equal("split", screen.state())
        f.manager.widget:hide()
        assert.are.equal("document", screen.state())
        require("agentic.session_registry").show_session(f.manager.session_key)
        assert.are.equal("split", screen.state())
        vim.api.nvim_win_close(editor(), true)
        assert.are.equal("conversation", screen.state())
        require("agentic.session_registry").destroy(f.manager.session_key)
        assert.are.equal("none", screen.state())
    end)

    it("treats a session shown in another tab as document in this one", function()
        local first = vim.api.nvim_get_current_tabpage()
        vim.cmd("tabnew")
        local second = vim.api.nvim_get_current_tabpage()
        assert.are.equal("document", screen.state(second))
        assert.are.equal("split", screen.state(first))
        assert.are.equal(first, f.manager.widget:get_visible_tab_id())
    end)

    it("opens the last document above the chat at half height without the chat's window options", function()
        vim.api.nvim_win_call(editor(), function()
            vim.cmd("edit " .. vim.fn.fnameescape(readme))
        end)
        local buf = vim.fn.bufnr(readme)
        vim.api.nvim_win_close(editor(), true)
        assert.are.equal("conversation", screen.state())
        local chat, current = f.manager.widget.win_nrs.chat, vim.api.nvim_get_current_win()
        assert.are_not.equal("", vim.wo[chat].winhighlight)
        local win = screen.ensure_document()
        assert.are.equal("split", screen.state())
        assert.are.equal(buf, vim.api.nvim_win_get_buf(win))
        assert.are.equal(half(), vim.api.nvim_win_get_height(win))
        assert.is_true(vim.fn.win_screenpos(win)[1] < vim.fn.win_screenpos(chat)[1])
        assert.are.equal(vim.fn.win_screenpos(chat)[2], vim.fn.win_screenpos(win)[2])
        assert.are.equal("", vim.wo[win].winhighlight)
        assert.are.equal(vim.go.statuscolumn, vim.wo[win].statuscolumn)
        assert.is_nil(vim.w[win].agentic_bufnr)
        assert.is_true(vim.wo[win].winfixheight)
        assert.are.equal(current, vim.api.nvim_get_current_win())
        assert.are.equal(win, screen.ensure_document())
    end)

    it("puts the document back at half height in split and leaves conversation alone", function()
        local doc = editor()
        vim.api.nvim_win_set_height(doc, 5)
        screen.resize()
        assert.are.equal(half(), vim.api.nvim_win_get_height(doc))
        vim.api.nvim_win_close(doc, true)
        local chat = f.manager.widget.win_nrs.chat
        local height = vim.api.nvim_win_get_height(chat)
        screen.resize()
        assert.are.equal(height, vim.api.nvim_win_get_height(chat))
        assert.are.equal("conversation", screen.state())
    end)

    it("holds the document height when a panel closes in split", function()
        local doc = editor()
        assert.are.equal(half(), vim.api.nvim_win_get_height(doc))
        assert.is_true(vim.wo[doc].winfixheight)
        f.manager.file_list:add(readme)
        assert.is_true(require("agentic.utils.buf_helpers").is_win_usable(f.manager.widget.win_nrs.files))
        f.manager.file_list:clear()
        assert.is_falsy(require("agentic.utils.buf_helpers").is_win_usable(f.manager.widget.win_nrs.files))
        assert.are.equal(half(), vim.api.nvim_win_get_height(doc))
    end)

    it("opens a new document above the chat when the only split beside it is a tool window", function()
        for _, filetype in ipairs({ "qf", "fugitive" }) do
            local tool = editor()
            vim.bo[vim.api.nvim_win_get_buf(tool)].filetype = filetype
            assert.are.equal("split", screen.state())
            assert.is_nil(screen.document_window())
            local win = screen.ensure_document()
            assert.are_not.equal(tool, win)
            assert.is_true(vim.fn.win_screenpos(win)[1] < vim.fn.win_screenpos(f.manager.widget.win_nrs.chat)[1])
            vim.api.nvim_win_close(win, true)
        end
    end)

    local function cycle()
        for _, mapping in ipairs(require("sodium.plugins.agentic").keys) do
            if mapping[1] == "<leader>ac" then return mapping[2]() end
        end
        error("missing current mapping")
    end

    it("cycles split, document and conversation with <leader>ac and keeps the document buffer", function()
        vim.api.nvim_win_call(editor(), function()
            vim.cmd("edit " .. vim.fn.fnameescape(readme))
        end)
        local buf = vim.fn.bufnr(readme)
        assert.are.equal("split", screen.state())
        cycle()
        assert.are.equal("document", screen.state())
        assert.are.same({ editor() }, screen.documents())
        assert.is_false(vim.wo[editor()].winfixheight)
        cycle()
        assert.are.equal("conversation", screen.state())
        assert.are.equal(vim.api.nvim_get_current_tabpage(), f.manager.widget:get_visible_tab_id())
        cycle()
        assert.are.equal("split", screen.state())
        assert.are.equal(buf, vim.api.nvim_win_get_buf(editor()))
        assert.are.equal(editor(), vim.api.nvim_get_current_win())
    end)

    it("closes every split beside the chat when the cycle leaves document", function()
        cycle()
        vim.cmd("split")
        vim.cmd("copen")
        assert.are.equal(3, #screen.documents())
        cycle()
        assert.are.equal("conversation", screen.state())
        assert.are.same({}, screen.documents())
    end)

    it("moves a session shown in another tab into this one as split and keeps every window here", function()
        local first = vim.api.nvim_get_current_tabpage()
        vim.cmd("tabnew")
        vim.cmd("edit " .. vim.fn.fnameescape(readme))
        vim.cmd("vsplit")
        vim.cmd("split")
        local second, wins = vim.api.nvim_get_current_tabpage(), vim.api.nvim_tabpage_list_wins(0)
        assert.are.equal(3, #wins)
        assert.are.equal(first, f.manager.widget:get_visible_tab_id())
        assert.are.equal("document", screen.state())
        cycle()
        assert.are.equal(second, f.manager.widget:get_visible_tab_id())
        assert.are.equal("split", screen.state())
        for _, win in ipairs(wins) do assert.is_true(vim.api.nvim_win_is_valid(win)) end
    end)

    it("leaves a quickfix window's own fixed height alone and clears only the held document outside split", function()
        local doc = editor()
        vim.cmd("copen")
        local qf = vim.api.nvim_get_current_win()
        assert.is_true(vim.wo[qf].winfixheight)
        screen.resize()
        assert.is_true(vim.wo[doc].winfixheight)
        f.manager.widget:hide()
        assert.are.equal("document", screen.state())
        assert.is_false(vim.wo[doc].winfixheight)
        assert.is_true(vim.wo[qf].winfixheight)
    end)

    it("keeps the chat's share when a held document is split and resized", function()
        local doc, widget = editor(), f.manager.widget
        local before = vim.api.nvim_win_get_height(widget.win_nrs.chat)
        vim.api.nvim_set_current_win(doc)
        vim.cmd("split")
        screen.resize()
        local chat = vim.api.nvim_win_get_height(widget.win_nrs.chat)
        assert.is_true(chat >= before - 1, "chat height " .. chat .. " was " .. before)
        assert.is_true(vim.api.nvim_win_get_height(0) >= half() / 2 - 1)
        for _, win in ipairs(screen.documents()) do
            if win ~= vim.api.nvim_get_current_win() then assert.is_false(vim.wo[win].winfixheight) end
        end
    end)

    it("finds no manager without loading agentic when no session registry exists", function()
        local loaded = package.loaded["agentic.session_registry"]
        package.loaded["agentic.session_registry"] = nil
        local ok, manager = pcall(screen.manager)
        local after = package.loaded["agentic.session_registry"]
        package.loaded["agentic.session_registry"] = loaded
        assert.is_true(ok)
        assert.is_nil(manager)
        assert.is_nil(after)
    end)

    it("gives conversation with a taller chat when the document closes in split", function()
        local chat = f.manager.widget.win_nrs.chat
        local height = vim.api.nvim_win_get_height(chat)
        vim.api.nvim_win_close(editor(), true)
        assert.are.equal("conversation", screen.state())
        assert.is_true(vim.api.nvim_win_get_height(chat) > height)
    end)

    local function chat_key(key, text)
        f.flush()
        local chat = f.manager.widget.win_nrs.chat
        local buf = vim.api.nvim_win_get_buf(chat)
        vim.bo[buf].modifiable = true
        vim.api.nvim_buf_set_lines(buf, 0, -1, false, { "see " .. text })
        vim.api.nvim_set_current_win(chat)
        vim.api.nvim_win_set_cursor(chat, { 1, 5 })
        vim.fn.maparg(key, "n", false, true).callback()
        f.flush()
        return chat, buf
    end
    local function in_document(chat, buf, line, file)
        local doc = vim.api.nvim_get_current_win()
        assert.are.equal("split", screen.state())
        assert.is_nil(vim.w[doc].agentic_bufnr)
        assert.are.equal(vim.fn.bufnr(file or readme), vim.api.nvim_win_get_buf(doc))
        if line then assert.are.equal(line, vim.api.nvim_win_get_cursor(doc)[1]) end
        assert.are.equal(buf, vim.api.nvim_win_get_buf(chat))
        assert.are.same({ 1, 5 }, vim.api.nvim_win_get_cursor(chat))
        return doc
    end
    local function home_note()
        vim.env.HOME = vim.fn.tempname()
        vim.fn.mkdir(vim.env.HOME, "p")
        local note = vim.env.HOME .. "/note.md"
        vim.fn.writefile({ "one", "two", "three" }, note)
        return note
    end

    it("opens a chat path reference in a new document window from conversation", function()
        vim.api.nvim_win_close(editor(), true)
        assert.are.equal("conversation", screen.state())
        local chat, buf = chat_key("gf", "README.md:3")
        local doc = in_document(chat, buf, 3)
        assert.is_true(vim.fn.win_screenpos(doc)[1] < vim.fn.win_screenpos(chat)[1])
    end)

    it("opens a chat path reference in the existing document window from split", function()
        local doc, count = editor(), #vim.api.nvim_tabpage_list_wins(0)
        local chat, buf = chat_key("gf", "README.md:3")
        assert.are.equal(doc, in_document(chat, buf, 3))
        assert.are.equal(count, #vim.api.nvim_tabpage_list_wins(0))
        local note = home_note()
        chat_key("gf", "~/note.md:2")
        assert.are.equal(doc, in_document(chat, buf, 2, note))
    end)

    it("opens a bare chat path through the gF fallback in the document window", function()
        vim.api.nvim_win_close(editor(), true)
        local chat, buf = chat_key("gf", "README.md")
        local doc = in_document(chat, buf)
        assert.are.equal(half(), vim.api.nvim_win_get_height(doc))
        assert.is_true(vim.wo[doc].winfixheight)
        local note = home_note()
        chat_key("gf", "~/note.md")
        assert.are.equal(doc, in_document(chat, buf, nil, note))
        vim.env.D3_NOTE_DIR = vim.env.HOME
        chat_key("gf", "$D3_NOTE_DIR/note.md:3")
        assert.are.equal(doc, in_document(chat, buf, 3, note))
    end)

    it("opens a picked file from the chat in the document window at its line", function()
        vim.api.nvim_win_close(editor(), true)
        f.flush()
        local chat = f.manager.widget.win_nrs.chat
        local buf = vim.api.nvim_win_get_buf(chat)
        vim.api.nvim_set_current_win(chat)
        local cursor = vim.api.nvim_win_get_cursor(chat)
        local picker = Snacks.picker({ items = { { file = readme, text = "README.md", pos = { 3, 0 } } } })
        assert.is_true(vim.wait(2000, function() return picker:current() ~= nil end))
        assert.are.equal(chat, picker.main)
        local action = require("snacks.picker.core.actions").resolve("confirm", picker)
        action.action(picker, picker:current(), action)
        assert.is_true(vim.wait(5000, function()
            local win = vim.api.nvim_get_current_win()
            return picker.preview == nil and vim.api.nvim_win_get_buf(win) == vim.fn.bufnr(readme)
                and vim.deep_equal({ 3, 0 }, vim.api.nvim_win_get_cursor(win))
        end, 10))
        local doc = vim.api.nvim_get_current_win()
        assert.are.equal("split", screen.state())
        assert.is_nil(vim.w[doc].agentic_bufnr)
        assert.are.equal(vim.fn.bufnr(readme), vim.api.nvim_win_get_buf(doc))
        assert.are.same({ 3, 0 }, vim.api.nvim_win_get_cursor(doc))
        assert.are.equal(buf, vim.api.nvim_win_get_buf(chat))
        assert.are.same(cursor, vim.api.nvim_win_get_cursor(chat))
    end)
    it("keeps a picker jump to a chat buffer line in the chat", function()
        vim.api.nvim_win_close(editor(), true)
        f.flush()
        local chat = f.manager.widget.win_nrs.chat
        local buf = vim.api.nvim_win_get_buf(chat)
        vim.api.nvim_set_current_win(chat)
        local picker = Snacks.picker({ items = { { buf = buf, text = "line", pos = { 1, 0 } } } })
        assert.is_true(vim.wait(2000, function() return picker:current() ~= nil end))
        local action = require("snacks.picker.core.actions").resolve("confirm", picker)
        action.action(picker, picker:current(), action)
        f.flush()
        assert.are.equal("conversation", screen.state())
        assert.are.equal(chat, vim.api.nvim_get_current_win())
        assert.are.equal(buf, vim.api.nvim_win_get_buf(chat))
    end)
    local Registry = require("agentic.session_registry")
    local function add_context()
        require("sodium.agency").add_context()
        f.flush()
    end
    local function new_session()
        local previous = f.manager
        vim.ui.select = function(items, _, callback) callback(items[1]) end
        for _, mapping in ipairs(require("sodium.plugins.agentic").keys) do
            if mapping[1] == "<leader>an" then mapping[2]() end
        end
        f.flush()
        f.client:_handle_message({ id = f.request("agency/backends").id, result = { defaultBackendId = "codex-acp", backends = { { id = "codex-acp",
            discovery = "fresh", defaults = {}, models = { { id = "model-c", name = "C", selection = { configValues = { model = "model-c" } } } } } } } })
        f.flush()
        vim.cmd.stopinsert()
        local manager = Registry.current()
        assert.are_not.equal(previous, manager)
        assert.is_true(manager.widget:is_open())
        assert.are.equal(vim.api.nvim_get_current_tabpage(), manager.widget:get_visible_tab_id())
        assert.is_false(previous.widget:is_open())
        assert.are.equal(previous, Registry.get(previous.session_key))
        local target = require("fixtures.agency_control").target_b
        f.client:_handle_message({ id = f.request("session/new").id, result = { sessionId = "agency:" .. target.agentId, _meta = { agency = { version = 1,
            binding = target, backendId = "codex-acp", configuration = { configOptions = {}, availableCommands = {} } } } } })
        f.flush()
        assert.are.equal(manager, Registry.current())
        assert.are.same(target, manager._agency_binding)
        assert.is_falsy(previous._destroyed)
        return manager
    end
    local function document_with_readme()
        f.flush()
        local doc = editor()
        vim.api.nvim_set_current_win(doc)
        vim.cmd("edit " .. vim.fn.fnameescape(readme))
        return doc
    end

    it("switches document to split when context is added and keeps the document", function()
        local doc = document_with_readme()
        f.manager.widget:hide()
        assert.are.equal("document", screen.state())
        add_context()
        assert.are.equal("split", screen.state())
        assert.are.same({ doc }, screen.documents())
        assert.are.equal(vim.fn.bufnr(readme), vim.api.nvim_win_get_buf(doc))
        assert.are.equal(doc, vim.api.nvim_get_current_win())
        assert.is_true(vim.fn.win_screenpos(doc)[1] < vim.fn.win_screenpos(f.manager.widget.win_nrs.chat)[1])
        assert.are.same({ vim.fn.fnamemodify(readme, ":p") }, f.manager.file_list:get_files())
        assert.are.equal(half(), vim.api.nvim_win_get_height(doc))
        f.manager.file_list:clear()
        assert.is_falsy(require("agentic.utils.buf_helpers").is_win_usable(f.manager.widget.win_nrs.files))
        assert.are.equal(half(), vim.api.nvim_win_get_height(doc))
    end)

    it("gives conversation when context is added from a document that is only the untouched scratch fallback", function()
        vim.api.nvim_win_close(editor(), true)
        f.manager.widget:hide()
        assert.are.equal("document", screen.state())
        local scratch = screen.documents()
        assert.are.equal(1, #scratch)
        assert.is_not_nil(vim.w[scratch[1]].agentic_fallback_bufnr)
        add_context()
        assert.are.equal("conversation", screen.state())
        assert.is_false(vim.api.nvim_win_is_valid(scratch[1]))
        assert.is_true(f.manager.code_selection:is_empty())
        assert.are.same({}, f.manager.file_list:get_files())
    end)

    for _, from in ipairs({ "conversation", "split" }) do
        it("moves a session shown in another tab in " .. from .. " into this tab when context is added", function()
            f.flush()
            local first, kept = vim.api.nvim_get_current_tabpage(), nil
            if from == "conversation" then vim.api.nvim_win_close(editor(), true) else kept = document_with_readme() end
            assert.are.equal(from, screen.state())
            vim.cmd("tabnew")
            vim.cmd("edit " .. vim.fn.fnameescape(readme))
            local doc = vim.api.nvim_get_current_win()
            assert.are.equal("document", screen.state())
            add_context()
            assert.are.equal(vim.api.nvim_get_current_tabpage(), f.manager.widget:get_visible_tab_id())
            assert.are.equal("split", screen.state())
            assert.are.same({ doc }, screen.documents())
            assert.are.equal(doc, vim.api.nvim_get_current_win())
            assert.are.equal("document", screen.state(first))
            if kept then assert.are.same({ kept }, screen.documents(first)) end
            assert.are.equal(2, #vim.api.nvim_list_tabpages())
            assert.are.same({ vim.fn.fnamemodify(readme, ":p") }, f.manager.file_list:get_files())
        end)
    end

    it("moves a session shown in another tab into a tab that holds only the scratch fallback and gives conversation", function()
        f.flush()
        local first = vim.api.nvim_get_current_tabpage()
        vim.cmd("tabnew")
        local second = vim.api.nvim_get_current_tabpage()
        Registry.show_session(f.manager.session_key, { focus_prompt = false })
        vim.api.nvim_win_close(editor(), true)
        assert.are.equal("conversation", screen.state())
        vim.api.nvim_set_current_tabpage(first)
        Registry.show_session(f.manager.session_key, { focus_prompt = false })
        assert.are.equal(first, f.manager.widget:get_visible_tab_id())
        vim.api.nvim_set_current_tabpage(second)
        local scratch = screen.documents()
        assert.are.equal(1, #scratch)
        assert.is_not_nil(vim.w[scratch[1]].agentic_fallback_bufnr)
        assert.are.equal("document", screen.state())
        add_context()
        assert.are.equal(second, f.manager.widget:get_visible_tab_id())
        assert.are.equal("conversation", screen.state())
        assert.is_false(vim.api.nvim_win_is_valid(scratch[1]))
        assert.is_true(f.manager.code_selection:is_empty())
        assert.are.same({}, f.manager.file_list:get_files())
    end)

    it("keeps conversation when a new session starts from conversation", function()
        vim.api.nvim_win_close(editor(), true)
        assert.are.equal("conversation", screen.state())
        new_session()
        assert.are.equal("conversation", screen.state())
        assert.are.same({}, screen.documents())
    end)

    it("keeps split and its document when a new session starts from split", function()
        local doc = document_with_readme()
        assert.are.equal("split", screen.state())
        new_session()
        assert.are.equal("split", screen.state())
        assert.are.same({ doc }, screen.documents())
        assert.are.equal(vim.fn.bufnr(readme), vim.api.nvim_win_get_buf(doc))
        assert.are.equal(half(), vim.api.nvim_win_get_height(doc))
    end)

    it("shows a new session started from document as split beside the document", function()
        local doc = document_with_readme()
        f.manager.widget:hide()
        assert.are.equal("document", screen.state())
        new_session()
        assert.are.equal("split", screen.state())
        assert.are.same({ doc }, screen.documents())
        assert.are.equal(vim.fn.bufnr(readme), vim.api.nvim_win_get_buf(doc))
        assert.are.equal(half(), vim.api.nvim_win_get_height(doc))
    end)

    it("commits a reattach from conversation and stays in conversation", function()
        vim.api.nvim_win_close(editor(), true)
        assert.are.equal("conversation", screen.state())
        local control, source = require("fixtures.agency_control"), f.manager
        local moved = vim.deepcopy(control.target_a)
        moved.handlerGeneration, moved.providerGeneration = control.id(20), control.id(21)
        local row = control.agent(moved)
        row.record.definition.cwd = vim.fn.getcwd()
        local target = require("sodium.agency.rebind").reattach(source, row)
        f.flush()
        local frame = f.request("session/load")
        f.client:_handle_message({ id = frame.id, result = { sessionId = "agency:" .. moved.agentId, _meta = { agency = { version = 1,
            binding = moved, backendId = "codex-acp", configuration = { configOptions = {}, availableCommands = {} } } } } })
        f.flush()
        assert.is_true(source._destroyed)
        assert.are.equal(target, Registry.current())
        assert.are.equal(vim.api.nvim_get_current_tabpage(), target.widget:get_visible_tab_id())
        assert.are.same(moved, target._agency_binding)
        assert.are.equal("conversation", screen.state())
        assert.are.same({}, screen.documents())
    end)

    it("starts or opens a session from a tab holding only an empty window as conversation", function()
        local first = vim.api.nvim_get_current_tabpage()
        f.manager.widget:hide()
        local function reclaimed(win, buf)
            assert.are.equal("conversation", screen.state())
            assert.is_false(vim.api.nvim_win_is_valid(win))
            assert.is_false(vim.api.nvim_buf_is_valid(buf))
            local input = Registry.current().widget.win_nrs.input
            assert.are.equal(vim.o.lines - vim.o.cmdheight, vim.fn.win_screenpos(input)[1] + vim.api.nvim_win_get_height(input))
        end
        vim.cmd("tabnew")
        local empty = vim.api.nvim_get_current_win()
        local buf = vim.api.nvim_get_current_buf()
        new_session()
        reclaimed(empty, buf)
        vim.cmd("tabnew")
        empty, buf = vim.api.nvim_get_current_win(), vim.api.nvim_get_current_buf()
        require("sodium.agency").open(f.row)
        f.flush()
        assert.are.equal(f.manager, Registry.current())
        assert.are.equal(vim.api.nvim_get_current_tabpage(), f.manager.widget:get_visible_tab_id())
        reclaimed(empty, buf)
        assert.are.equal(3, #vim.api.nvim_list_tabpages())
        assert.are.equal("document", screen.state(first))
    end)

    for _, how in ipairs({ "open", "new" }) do
        it("keeps an empty window made beside a visible conversation when a session is " .. how .. "ed", function()
            f.flush()
            vim.api.nvim_win_close(editor(), true)
            assert.are.equal("conversation", screen.state())
            vim.cmd("new")
            f.flush()
            local scratch = vim.api.nvim_get_current_win()
            local buf = vim.api.nvim_win_get_buf(scratch)
            if how == "open" then require("sodium.agency").open(); f.flush() else new_session() end
            assert.is_true(vim.api.nvim_win_is_valid(scratch))
            assert.is_true(vim.api.nvim_buf_is_valid(buf))
            assert.are.equal("split", screen.state())
        end)
    end

    it("rebalances split when the document is split without an explicit resize", function()
        f.flush()
        local doc, chat = editor(), f.manager.widget.win_nrs.chat
        local before = vim.api.nvim_win_get_height(chat)
        vim.api.nvim_set_current_win(doc)
        vim.cmd("split")
        f.flush()
        local height = vim.api.nvim_win_get_height(chat)
        assert.is_true(height >= before - 1, "chat height " .. height .. " was " .. before)
        assert.is_true(vim.fn.win_screenpos(vim.api.nvim_get_current_win())[1] < vim.fn.win_screenpos(chat)[1])
    end)

    local function above_chat(win)
        local chat = f.manager.widget.win_nrs.chat
        assert.is_true(vim.fn.win_screenpos(win)[1] < vim.fn.win_screenpos(chat)[1])
        assert.are.equal(vim.o.columns, vim.api.nvim_win_get_width(win))
        local input = f.manager.widget.win_nrs.input
        assert.are.equal(vim.o.lines - vim.o.cmdheight, vim.fn.win_screenpos(input)[1] + vim.api.nvim_win_get_height(input))
    end

    it("moves help opened from the chat in conversation above the chat as split", function()
        f.flush()
        vim.api.nvim_win_close(editor(), true)
        assert.are.equal("conversation", screen.state())
        vim.api.nvim_set_current_win(f.manager.widget.win_nrs.chat)
        vim.cmd("help")
        f.flush()
        local help = vim.api.nvim_get_current_win()
        assert.are.equal("help", vim.bo[vim.api.nvim_win_get_buf(help)].buftype)
        above_chat(help)
        assert.are.equal("split", screen.state())
        assert.is_true(vim.api.nvim_win_get_height(help) >= half() - 1)
    end)

    it("moves a split of the chat above the chat and leaves the widget windows alone", function()
        f.flush()
        local chat = f.manager.widget.win_nrs.chat
        vim.api.nvim_set_current_win(chat)
        vim.cmd("split")
        f.flush()
        local win = vim.api.nvim_get_current_win()
        assert.are_not.equal(chat, win)
        above_chat(win)
        assert.are.equal(chat, f.manager.widget.win_nrs.chat)
        assert.is_true(vim.api.nvim_win_is_valid(chat))
    end)
