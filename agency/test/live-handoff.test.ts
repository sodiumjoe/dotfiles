import assert from "node:assert/strict"
import test from "node:test"
import { readFile, rm, writeFile } from "node:fs/promises"
import { join } from "node:path"
import { liveHandlerFixture } from "./live-support.js"
import { createAgentIndex } from "../src/agent/agent-index.js"

const exists = (path: string) => readFile(path).then(() => true, () => false)
type Fixture = Awaited<ReturnType<typeof liveHandlerFixture>>
const rollout = (f: Fixture, sessionId: string) => join(f.homes, "codex/sessions/2026/11/14", "rollout-2026-11-14T10-00-00-" + sessionId + ".jsonl")
const live = async (f: Fixture) => new Map((await f.agents()).map(row => [row.agentId, row]))

test("a handoff brings the prompted agents back with their model and mode once the next Handler is ready", async t => {
  const f = await liveHandlerFixture(t), codex = await f.start(), claude = await f.start({ backendId: "claude-agent-acp" }), unprompted = await f.start()
  await f.prompt(codex.agentId, "hello"); await f.prompt(claude.agentId, "hello")
  await f.set(codex.agentId, "model", "model-b"); await f.set(codex.agentId, "mode", "read-only"); await f.set(claude.agentId, "mode", "review")
  assert.equal((await f.handoff()).ok, true)
  const written = JSON.parse(await readFile(join(f.paths.persistentRoot, "handoff.json"), "utf8"))
  assert.deepEqual([written.bootId, written.agents.map((agent: { agentId: string }) => agent.agentId).sort()], [await f.adapter.bootId(), [codex.agentId, claude.agentId].sort()])
  assert.deepEqual(Object.keys(written.agents[0]).sort(), ["agentId", "backendId", "createdAt", "cwd", "mode", "model", "nativeSessionId", "origin"])
  await f.restart()
  const settled = await f.settledHandoff()
  assert.deepEqual([settled.agents.sort(), settled.failed], [[codex.agentId, claude.agentId].sort(), []])
  const rows = await live(f)
  assert.deepEqual([rows.get(codex.agentId)?.live?.activity, rows.get(codex.agentId)?.live?.model, rows.get(codex.agentId)?.live?.mode], ["idle", "model-b", "read-only"])
  assert.deepEqual([rows.get(claude.agentId)?.live?.activity, rows.get(claude.agentId)?.live?.mode], ["idle", "review"])
  assert.equal(rows.has(unprompted.agentId), false)
  assert.equal(await exists(join(f.paths.persistentRoot, "handoff.json")), false)
  assert.equal((await f.prompt(codex.agentId, "again")).text, "answer:again")
  await f.verifyZeroSurvivors()
})

test("the next Handler is ready before its handoff restores finish, and a prompt during a restore shares it", async t => {
  const f = await liveHandlerFixture(t), { agentId } = await f.start()
  await f.prompt(agentId, "hello")
  assert.equal((await f.handoff()).ok, true)
  const [entry] = await createAgentIndex(f.paths.persistentRoot).list()
  await f.pauseSessions()
  await f.restart()
  await f.waitSession()
  assert.deepEqual([(await f.handoffStatus())?.pending, (await live(f)).get(agentId)?.live?.activity], [[agentId], "starting"])
  const prompted = f.prompt(agentId, "during")
  await f.releaseSessions()
  assert.equal((await prompted).text, "answer:during")
  assert.deepEqual((await f.settledHandoff()).failed, [])
  const loads = (await f.providerRequests()).filter(frame => frame.method === "session/load" && frame.params?.sessionId === entry!.nativeSessionId)
  assert.equal(loads.length, 1)
  await f.verifyZeroSurvivors()
})

test("a handoff waits for running turns, restores an agent whose index entry is missing, and leaves one whose session file is gone stopped", async t => {
  const f = await liveHandlerFixture(t), kept = await f.start(), lost = await f.start(), unindexed = await f.start()
  await f.prompt(kept.agentId, "hello"); await f.prompt(lost.agentId, "hello"); await f.prompt(unindexed.agentId, "hello")
  await f.pausePrompts()
  const running = f.prompt(kept.agentId, "slow")
  await f.waitPrompt()
  assert.equal((await f.handoff()).ok, false)
  assert.equal(await exists(join(f.paths.persistentRoot, "handoff.json")), false)
  await f.releasePrompts()
  await running
  assert.equal((await f.handoff()).ok, true)
  const index = createAgentIndex(f.paths.persistentRoot), entries = await index.list()
  await rm(rollout(f, entries.find(value => value.agentId === lost.agentId)!.nativeSessionId))
  await index.remove(unindexed.agentId)
  await f.restart()
  const settled = await f.settledHandoff()
  assert.deepEqual(settled.failed.map(item => [item.agentId, item.code]), [[lost.agentId, "NOT_FOUND"]])
  const rows = await live(f)
  assert.deepEqual([rows.get(kept.agentId)?.live?.activity, rows.get(unindexed.agentId)?.live?.activity, rows.get(lost.agentId)?.live], ["idle", "idle", null])
  assert.ok((await index.list()).some(value => value.agentId === unindexed.agentId))
  assert.ok((await f.events()).some(event => event.type === "handoff_restore_failed" && event.agentId === lost.agentId))
  await f.verifyZeroSurvivors()
})

test("a handoff from another boot or older than ten minutes is ignored, and a bad entry is dropped while the rest restore", async t => {
  const f = await liveHandlerFixture(t), { agentId } = await f.start()
  await f.prompt(agentId, "hello")
  await f.stopHandler()
  assert.equal(await exists(join(f.paths.persistentRoot, "handoff.json")), false)
  const [entry] = await createAgentIndex(f.paths.persistentRoot).list()
  const agent = { agentId, backendId: entry!.backendId, nativeSessionId: entry!.nativeSessionId, cwd: entry!.cwd, createdAt: entry!.createdAt, origin: entry!.origin, model: null, mode: "read-only" }
  const write = (bootId: string, writtenAt: Date, agents: unknown[]) => writeFile(join(f.paths.persistentRoot, "handoff.json"), JSON.stringify({ version: 1, handlerGeneration: "older", bootId, writtenAt: writtenAt.toISOString(), agents }), { mode: 0o600 })
  const bootId = await f.adapter.bootId()
  for (const [boot, at, reason] of [["another-boot", new Date(), /boot/], [bootId, new Date(Date.now() - 11 * 60 * 1000), /seconds old/]] as const) {
    await write(boot, at, [agent])
    await f.restart()
    assert.equal(await f.handoffStatus(), undefined)
    assert.equal((await live(f)).get(agentId)?.live, null)
    assert.equal(await exists(join(f.paths.persistentRoot, "handoff.json")), false)
    assert.match(String((await f.events()).filter(event => event.type === "handoff_ignored").at(-1)?.reason), reason)
    await f.stopHandler()
  }
  await write(bootId, new Date(), [{ agentId: "not-an-agent" }, agent])
  await f.restart()
  assert.deepEqual((await f.settledHandoff()).failed, [])
  assert.deepEqual((await live(f)).get(agentId)?.live?.mode, "read-only")
  assert.deepEqual((await f.events()).filter(event => event.type === "handoff_entry_dropped").map(event => event.index), [0])
  await f.verifyZeroSurvivors()
})

test("an unreadable handoff file restores nothing, and a handoff whose drain fails after stopping agents is kept for the next start", async t => {
  const f = await liveHandlerFixture(t), first = await f.start(), second = await f.start()
  await f.prompt(first.agentId, "hello"); await f.prompt(second.agentId, "hello")
  await writeFile(join(f.root, "fail-catalog-drain"), "fail", { mode: 0o600 })
  assert.equal((await f.handoff()).ok, false)
  assert.equal(await exists(join(f.paths.persistentRoot, "handoff.json")), true)
  assert.deepEqual([...(await live(f)).values()].map(row => row.live), [null, null])
  assert.ok((await f.events()).some(event => event.type === "handoff_kept"))
  await rm(join(f.root, "fail-catalog-drain"))
  await f.stopHandler()
  await f.restart()
  assert.deepEqual((await f.settledHandoff()).agents.sort(), [first.agentId, second.agentId].sort())
  assert.deepEqual([...(await live(f)).values()].map(row => row.live?.activity), ["idle", "idle"])
  await f.stopHandler()
  await writeFile(join(f.paths.persistentRoot, "handoff.json"), "{not json", { mode: 0o600 })
  await f.restart()
  assert.equal(await f.handoffStatus(), undefined)
  assert.deepEqual([...(await live(f)).values()].map(row => row.live), [null, null])
  assert.equal(await exists(join(f.paths.persistentRoot, "handoff.json")), false)
  assert.ok((await f.events()).some(event => event.type === "handoff_unreadable"))
  await f.verifyZeroSurvivors()
})